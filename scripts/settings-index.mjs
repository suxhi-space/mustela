// Builds src/ui/settings/searchIndex.ts: every setting's label on each Settings page, for Settings search.
// Run: node scripts/settings-index.mjs   (src/ui/settings/searchIndex.test.ts checks it's up to date)
import { readFileSync, writeFileSync } from "node:fs";
export const PAGES = {
  account: "MyAccount", sessions: "Sessions", bots: "Bots", voice: "VoiceVideo", soundboard: "SoundboardSettings",
  appearance: "Appearance", accessibility: "AccessibilityPage", notifications: "Notifications", language: "Language",
  desktop: "DesktopPage", activity: "ActivityPage", performance: "PerformancePage", sync: "MustelaSync", accounts: "AccountsPage", advanced: "Advanced",
};
const EXTRA = { appearance: ["themes.tsx"] };
export function labelsOf(src) {
  const out = new Set();
  for (const m of src.matchAll(/<(?:Row|Group)\b[^>]*?\b(?:label|title)="([^"{}]{2,60})"/g)) {
    const l = m[1].trim();
    // Placeholders and empty states aren't settings.
    if (!l.endsWith("…") && !/^No /.test(l)) out.add(l);
  }
  return [...out];
}
export function build(root = ".") {
  const idx = {};
  for (const [tab, file] of Object.entries(PAGES)) {
    const files = [`${file}.tsx`, ...(EXTRA[tab] ?? [])];
    idx[tab] = [...new Set(files.flatMap((f) => labelsOf(readFileSync(`${root}/src/ui/settings/${f}`, "utf8"))))];
  }
  return idx;
}
export const render = (idx) => `// Generated by scripts/settings-index.mjs from each Settings page's labels. Don't edit by hand.\nexport const SETTING_LABELS: Record<string, string[]> = ${JSON.stringify(idx, null, 2)};\n`;
if (import.meta.url === `file://${process.argv[1]}`) { writeFileSync("src/ui/settings/searchIndex.ts", render(build())); console.log("written"); }
